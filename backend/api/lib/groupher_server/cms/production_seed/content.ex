defmodule GroupherServer.CMS.ProductionSeed.Content do
  @moduledoc """
  Creates the deterministic acceptance dataset through domain Commands.

      Trusted Node artifact -> exact fixture contract -> locked run
        -> published Article/Doc + mirror + Comment + User Ticket -> manifest

  Bodies are generated by scripts/production-seed-bodybags.mts, never Factory.
  All writes and manifest ownership commit together. Replays reject modified data.
  Review decisions, model failures and browser acceptance remain real test actions.
  """
  alias GroupherServer.CMS.ProductionSeed
  alias GroupherServer.{Repo, CMS}
  alias GroupherServer.Accounts.Model.User
  alias CMS.Model.{Article, ArticleBinding, ArticlePublic, DocPublic, DocBranchVersion, Community}

  @fixtures [
              {"PX", :post, "dev"},
              {"BX", :blog, "dev"},
              {"CX", :changelog, "dev"},
              {"DX", :doc, "dev"},
              {"shared", :post, "dev"},
              {"deleteProbe", :post, "tmp"},
              {"zero", :post, "dev"},
              {"self", :post, "dev"},
              {"reviewImmediate", :post, "dev"},
              {"reviewAI", :post, "dev"},
              {"reviewHuman", :post, "mock"}
            ] ++ Enum.map(1..21, &{"page#{&1}", :post, "dev"})

  @doc "Seeds a fixed Node-published artifact on the explicitly admitted database."
  def apply(run_id, database, path) when is_binary(path) do
    with {:ok, _} <- ProductionSeed.admit(database),
         {:ok, %{type: :regular, size: size}} when size <= 2_000_000 <- File.stat(path),
         {:ok, bytes} <- File.read(path),
         {:ok, input} <- Jason.decode(bytes),
         true <- input["runId"] == run_id and valid_input?(input) do
      Repo.transaction(
        fn ->
          ProductionSeed.advisory_lock!()
          run = ProductionSeed.lock!(run_id)
          checksum = Base.encode16(:crypto.hash(:sha256, bytes), case: :lower)

          case run.manifest["contentChecksum"] do
            nil -> seed!(run, input, checksum)
            ^checksum -> verify_snapshot!(run.manifest)
            _ -> Repo.rollback(:seed_artifact_changed)
          end

          {:ok, manifest} = ProductionSeed.report(run_id, database)
          manifest
        end,
        timeout: 120_000
      )
    else
      _ -> {:error, :seed_invalid_artifact}
    end
  end

  def apply(_, _, _), do: {:error, :seed_invalid_artifact}

  defp valid_input?(%{"schemaVersion" => 1, "entries" => entries, "commentBodyBag" => body})
       when is_list(entries) and is_map(body) do
    expected = Enum.map(@fixtures, fn {name, thread, slug} -> {name, to_string(thread), slug} end)

    Enum.all?(entries, &is_map/1) and
      Enum.map(entries, &{&1["alias"], &1["thread"], &1["community"]}) == expected and
      Enum.all?(entries, &(is_map(&1["bodyBag"]) and is_binary(&1["title"])))
  end

  defp valid_input?(_), do: false

  defp seed!(run, input, checksum) do
    commands = input["commands"] || Repo.rollback(:seed_missing_command_ids)
    unless is_map(commands), do: Repo.rollback(:seed_invalid_command_ids)

    required =
      Enum.map(@fixtures, fn {name, _, _} -> "article-#{name}" end) ++
        ~w(mirror-shared mirror-deleteProbe comment-CM comment-sharedComment comment-deleteProbeComment comment-docComment ticket-create ticket-publish ticket-cleanup-withdraw)

    unless Enum.all?(required, &match?({:ok, _}, Ecto.UUID.cast(commands[&1]))) do
      Repo.rollback(:seed_invalid_command_ids)
    end

    actor = Repo.get!(User, run.manifest["users"]["author"])
    admin = Repo.get!(User, run.manifest["users"]["adminDev"])
    {:ok, passport} = CMS.Passport.get_passport(admin)
    admin = %{admin | cur_passport: passport}

    communities =
      Map.new(run.manifest["communities"], fn {slug, id} -> {slug, Repo.get!(Community, id)} end)

    resources =
      Enum.zip(@fixtures, input["entries"])
      |> Map.new(fn {{name, thread, slug}, attrs} ->
        public =
          command!(
            CMS.Articles.create(
              communities[slug],
              thread,
              %{
                title: attrs["title"],
                slug:
                  "seed-#{String.downcase(name)}-#{Base.encode16(:crypto.hash(:sha256, run.run_id), case: :lower) |> String.slice(0, 12)}",
                body_bag: attrs["bodyBag"]
              },
              actor,
              command_id: commands["article-#{name}"]
            ),
            name
          )

        article = public.article
        {name, describe(article, communities[slug], public)}
      end)

    Enum.each(~w(shared deleteProbe), fn name ->
      source = communities[resources[name]["community"]]

      command!(
        CMS.Articles.mirror(
          communities["mock"],
          resources[name]["articleId"],
          [],
          admin,
          source,
          commands["mirror-#{name}"]
        ),
        "mirror-#{name}"
      )
    end)

    px = resources["PX"]
    shared = resources["shared"]

    comment =
      command!(
        CMS.Comments.create_comment(
          communities["dev"],
          :post,
          px["innerId"],
          input["commentBodyBag"],
          actor,
          commands["comment-CM"]
        )
      )

    shared_comment =
      command!(
        CMS.Comments.create_comment(
          communities["dev"],
          :post,
          shared["innerId"],
          input["commentBodyBag"],
          actor,
          commands["comment-sharedComment"]
        )
      )

    probe = resources["deleteProbe"]

    probe_comment =
      command!(
        CMS.Comments.create_comment(
          communities["tmp"],
          :post,
          probe["innerId"],
          input["commentBodyBag"],
          actor,
          commands["comment-deleteProbeComment"]
        )
      )

    dx = resources["DX"]

    doc_comment =
      command!(
        CMS.Comments.create_comment(
          communities["dev"],
          :doc,
          dx["innerId"],
          input["commentBodyBag"],
          actor,
          commands["comment-docComment"]
        )
      )

    ticket =
      command!(
        CMS.Tickets.create_from_post(
          communities["dev"],
          px["articleId"],
          %{title: "Acceptance TX", digest: "Production acceptance User Ticket"},
          admin,
          commands["ticket-create"]
        )
      )

    internal = command!(CMS.Tickets.get_internal(communities["dev"], ticket.id, admin))

    command!(
      CMS.Tickets.publish(
        communities["dev"],
        ticket.id,
        "Acceptance publication",
        internal.draft_version,
        internal.lifecycle_version,
        internal.workflow_version,
        admin,
        commands["ticket-publish"],
        CMS.Tickets.Publication.preview_anchor(communities["dev"].id, ticket.id)
      )
    )

    ticket_article = Repo.get!(Article, ticket.id)

    tx =
      describe(
        ticket_article,
        communities["dev"],
        Repo.get_by!(ArticlePublic, article_id: ticket_article.id)
      )
      |> Map.put("ticketId", ticket.id)

    resources =
      Map.merge(resources, %{
        "TX" => tx,
        "CM" => describe_comment(comment, px),
        "sharedComment" => describe_comment(shared_comment, shared),
        "docComment" => describe_comment(doc_comment, dx),
        "deleteProbeComment" => describe_comment(probe_comment, probe)
      })

    manifest =
      Map.merge(run.manifest, %{
        "resources" => resources,
        "contentChecksum" => checksum,
        "artifactRevision" => input["revision"],
        "seedVersion" => 1,
        "commands" => commands,
        "retention" => "demo_content_requires_explicit_cleanup_policy"
      })

    run |> Ecto.Changeset.change(manifest: manifest) |> Repo.update!()
    manifest
  end

  defp describe(article, community, public) do
    binding = Repo.get_by!(ArticleBinding, article_id: article.id, community_id: community.id)

    %{
      "articleId" => article.id,
      "branchId" => Map.get(public, :branch_id),
      "thread" => to_string(article.thread),
      "community" => community.slug,
      "innerId" => binding.inner_id,
      "revisionId" => Map.get(public, :revision_id),
      "disposable" => community.slug == "tmp",
      "url" =>
        CMS.FrontDesk.article_url(%{
          community_slug: community.slug,
          thread: article.thread,
          inner_id: binding.inner_id,
          slug: Map.get(public, :slug)
        }),
      "locator" => %{
        "community" => community.slug,
        "thread" => to_string(article.thread),
        "innerId" => binding.inner_id
      }
    }
  end

  defp describe_comment(comment, article) do
    %{
      "commentId" => comment.id,
      "bodyVersion" => Repo.get_by!(CMS.Model.CommentBody, comment_id: comment.id).version,
      "articleId" => comment.article_id,
      "innerId" => comment.inner_id,
      "thread" => "comment",
      "community" => article["community"],
      "url" => article["url"] <> "#comment-#{comment.inner_id}",
      "locator" => Map.put(article["locator"], "commentInnerId", comment.inner_id)
    }
  end

  @doc "Rejects edited or deleted fixtures before replaying an operational seed. Authoritative rows -> manifest revision/version comparison. Builds no projection."
  def verify_snapshot!(manifest) do
    Enum.each(manifest["resources"], fn {_name, resource} ->
      community = Repo.get_by(Community, slug: resource["community"])

      binding =
        community &&
          Repo.get_by(ArticleBinding,
            article_id: resource["articleId"],
            community_id: community.id
          )

      unless binding && binding.inner_id == resource["locator"]["innerId"] do
        Repo.rollback(:seed_binding_changed)
      end

      cond do
        resource["commentId"] ->
          body = Repo.get_by(CMS.Model.CommentBody, comment_id: resource["commentId"])

          lifecycle = Repo.get_by(CMS.Model.CommentLifecycle, comment_id: resource["commentId"])

          unless body && body.version == resource["bodyVersion"] && lifecycle &&
                   lifecycle.state == :visible do
            Repo.rollback(:seed_content_changed)
          end

        resource["revisionId"] ->
          public =
            if resource["thread"] == "doc" do
              Repo.get_by(DocPublic,
                article_id: resource["articleId"],
                branch_id: resource["branchId"]
              )
            else
              Repo.get_by(ArticlePublic, article_id: resource["articleId"])
            end

          revision_id =
            if resource["thread"] == "doc" and public do
              Repo.get!(DocBranchVersion, public.branch_version_id).revision_id
            else
              public && public.revision_id
            end

          unless revision_id == resource["revisionId"] do
            Repo.rollback(:seed_content_changed)
          end

        true ->
          unless Repo.get(Article, resource["articleId"]) do
            Repo.rollback(:seed_content_changed)
          end
      end
    end)

    manifest
  end

  defp command!(result, label \\ "domain")
  defp command!({:ok, result}, _label), do: result
  defp command!({:error, reason}, label), do: Repo.rollback({:seed_command_failed, label, reason})
end
