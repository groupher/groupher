import { readFile, writeFile } from 'node:fs/promises'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const source = JSON.parse(await readFile(new URL('gate.contract.json', root), 'utf8'))
const tsTarget = new URL('src/gate.generated.ts', root)
const exTarget = new URL('../../backend/api/lib/groupher_server/cms/gate_action.ex', root)

const keyFor = (action) => action.replaceAll('.', '_').toUpperCase()
const functionFor = (action) => action.replaceAll('.', '_')
const globalActions = new Set(source.globalActions)
const ownerFallbackActions = new Set(source.ownerFallbackActions)
const ownerOnlyActions = new Set(source.ownerOnlyActions)

const requirementFor = (action) => {
  const requirement = {}
  if (!ownerOnlyActions.has(action)) {
    requirement.scope = globalActions.has(action) ? 'global' : 'context'
    if (requirement.scope === 'context') requirement.context = 'cms'

    const threadGrantSuffix = source.threadGrantSuffixes[action]
    if (threadGrantSuffix) requirement.grantByThread = threadGrantSuffix
    else requirement.grant = source.grantAliases[action] ?? action
  }
  if (ownerFallbackActions.has(action)) requirement.ownerFallback = true
  return requirement
}

const tsActions = source.actions.map((action) => `  ${keyFor(action)}: '${action}',`).join('\n')
const tsRequirements = source.actions
  .map((action) => `  '${action}': ${JSON.stringify(requirementFor(action))},`)
  .join('\n')
const ts = `// Generated by scripts/generate-gate-contract.mjs. Do not edit directly.
export const GATE_ACTION = {
${tsActions}
} as const

export type TGateAction = (typeof GATE_ACTION)[keyof typeof GATE_ACTION]

export type TGateRequirement = {
  scope?: 'global' | 'context'
  context?: 'cms'
  grant?: string
  grantByThread?: string
  ownerFallback?: boolean
}

export const GATE_REQUIREMENT = {
${tsRequirements}
} as const satisfies Record<TGateAction, TGateRequirement>
`
const formattedTs = execFileSync(
  'pnpm',
  [
    'exec',
    'oxfmt',
    '-c',
    fileURLToPath(new URL('../../frontend/core/config/oxfmt.json', root)),
    `--stdin-filepath=${fileURLToPath(tsTarget)}`,
  ],
  { input: ts, encoding: 'utf8' },
)

const exFunctions = source.actions
  .map(
    (action) => `  @doc "Returns the stable \`${action}\` Gate action name."
  @spec ${functionFor(action)}() :: String.t()
  def ${functionFor(action)}, do: "${action}"`,
  )
  .join('\n\n')
const exActions = source.actions.map((action) => `    "${action}"`).join(',\n')
const exValue = (value) => (typeof value === 'boolean' ? value : `:${value}`)
const exRequirement = (action) => {
  const entries = Object.entries(requirementFor(action)).map(([key, value]) => {
    const exKey = key === 'grantByThread' ? 'grant_by_thread' : key === 'ownerFallback' ? 'owner_fallback' : key
    const renderedValue = key === 'grant' || key === 'grantByThread' ? `"${value}"` : exValue(value)
    return `${exKey}: ${renderedValue}`
  })
  return `%{${entries.join(', ')}}`
}
const exRequirements = source.actions
  .map((action) => `    "${action}" => ${exRequirement(action)}`)
  .join(',\n')
const ex = `# Generated by packages/contracts/scripts/generate-gate-contract.mjs. Do not edit directly.
defmodule GroupherServer.CMS.GateAction do
  @moduledoc """
  Generated action names shared by frontend Gate and Phoenix authorization.

      gate.contract.json
        -> TypeScript GATE_ACTION
        -> Phoenix GateAction
        -> Passport Registry parity check
  """

  @actions [
${exActions}
  ]

  @requirements %{
${exRequirements}
  }

  @doc "Returns every action registered by the cross-runtime Gate contract."
  @spec all() :: [String.t()]
  def all, do: @actions

  @doc "Returns the generated Passport requirement for a stable Gate action."
  @spec requirement(String.t()) :: map() | nil
  def requirement(action), do: Map.get(@requirements, action)

${exFunctions}
end
`

const outputs = [
  [tsTarget, formattedTs],
  [exTarget, ex],
]

if (process.argv.includes('--check')) {
  const mismatches = []
  for (const [target, expected] of outputs) {
    const actual = await readFile(target, 'utf8').catch(() => '')
    if (actual !== expected) mismatches.push(fileURLToPath(target))
  }
  if (mismatches.length) {
    console.error(`Generated Gate contract is stale:\n${mismatches.join('\n')}`)
    process.exitCode = 1
  }
} else {
  await Promise.all(outputs.map(([target, content]) => writeFile(target, content)))
}
