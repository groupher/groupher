import { execFileSync } from 'node:child_process'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

import { validateGateContract } from './validate-gate-contract.mjs'

const root = new URL('../', import.meta.url)
const repo = new URL('../../', root)
const source = JSON.parse(await readFile(new URL('gate.contract.json', root), 'utf8'))
const tsTarget = new URL('src/gate.generated.ts', root)
const exTarget = new URL('../../backend/api/lib/groupher_server/cms/gate_action.ex', root)

const config = await readFile(new URL('backend/api/config/config.exs', repo), 'utf8')
const articleSections = [
  ...config.matchAll(
    /config\s+:groupher_server,\s*:article,([\s\S]*?)(?=\nconfig\s|\nimport_config\s|$)/g,
  ),
]
if (articleSections.length !== 1) throw new Error('Expected exactly one Article config section')
const threadDeclarations = [
  ...articleSections[0][1].matchAll(/^\s*threads:\s*\[([^\]]*)\],?\s*$/gm),
]
if (threadDeclarations.length !== 1)
  throw new Error('Expected exactly one Article thread declaration')
const threadTokens = threadDeclarations[0][1].split(',').map((token) => token.trim())
if (!threadTokens.length || threadTokens.some((token) => !/^:[a-z][a-z0-9_]*$/.test(token))) {
  throw new Error('Invalid Article thread declaration')
}
const threads = threadTokens.map((token) => token.slice(1))
if (new Set(threads).size !== threads.length) throw new Error('Article threads must be distinct')

const permissions = validateGateContract(source, new Set(threads))
const keyFor = (action) => action.replaceAll('.', '_').toUpperCase()
const threadKeyFor = (thread) => thread.replaceAll('.', '_').toUpperCase()
const functionFor = (action) => action.replaceAll('.', '_')
const toTs = (value) => JSON.stringify(value)
const toElixirStringList = (values) =>
  `[${values.map((value) => JSON.stringify(value)).join(', ')}]`
const toElixirThreadMap = (entries) =>
  `%{${Object.entries(entries)
    .map(
      ([thread, dependencies]) =>
        `${JSON.stringify(thread)} => ${toElixirStringList(dependencies)}`,
    )
    .join(', ')}}`

const tsActions = permissions.map(({ action }) => `  ${keyFor(action)}: '${action}',`).join('\n')
const tsThreads = threads.map((thread) => `  ${threadKeyFor(thread)}: '${thread}',`).join('\n')
const tsMetadata = permissions
  .map(
    ({ action, scope, grantable, owner_only, requires, requires_thread }) =>
      `  '${action}': { scope: '${scope}', grantable: ${grantable}, owner_only: ${owner_only}, requires: ${toTs(requires)}, requires_thread: ${toTs(requires_thread)} },`,
  )
  .join('\n')
const ts = `// Generated by scripts/generate-gate-contract.mjs. Do not edit directly.
export const GATE_ACTION = {
${tsActions}
} as const

export type TGateAction = (typeof GATE_ACTION)[keyof typeof GATE_ACTION]
export type TGatePermissionScope = 'global' | 'community' | 'article'
export const GATE_THREAD = {
${tsThreads}
} as const
export type TGateThread = (typeof GATE_THREAD)[keyof typeof GATE_THREAD]

export type TGatePermission = {
  scope: TGatePermissionScope
  grantable: boolean
  owner_only: boolean
  requires: readonly TGateAction[]
  requires_thread: Partial<Record<TGateThread, readonly TGateAction[]>>
}

export const GATE_PERMISSION: Record<TGateAction, TGatePermission> = {
${tsMetadata}
}
`
const formattedTs = execFileSync(
  'pnpm',
  [
    'exec',
    'oxfmt',
    '-c',
    fileURLToPath(new URL('../../frontend/core/config/oxfmt.json', root)),
    `--stdin-filepath=${fileURLToPath(tsTarget)}`,
  ],
  { input: ts, encoding: 'utf8' },
)

const exFunctions = permissions
  .map(
    ({ action }) => `  @doc "Returns the stable \`${action}\` Gate action name."
  @spec ${functionFor(action)}() :: String.t()
  def ${functionFor(action)}, do: ${JSON.stringify(action)}`,
  )
  .join('\n\n')
const exActions = permissions.map(({ action }) => `    ${JSON.stringify(action)}`).join(',\n')
const exThreads = threads.map((thread) => `    ${JSON.stringify(thread)}`).join(',\n')
const exMetadata = permissions
  .map(({ action, scope, grantable, owner_only, requires, requires_thread }) => {
    const fields = [
      `scope: :${scope}`,
      `grantable: ${grantable}`,
      `owner_only: ${owner_only}`,
      `requires: ${toElixirStringList(requires)}`,
      `requires_thread: ${toElixirThreadMap(requires_thread)}`,
    ]
    return `    ${JSON.stringify(action)} => %{
${fields.map((field) => `      ${field}`).join(',\n')}
    }`
  })
  .join(',\n')
const ex = `# Generated by packages/contracts/scripts/generate-gate-contract.mjs. Do not edit directly.
defmodule GroupherServer.CMS.GateAction do
  @moduledoc """
  Generated action names and permission metadata shared by Phoenix and frontend Gate.

      gate.contract.json
        -> TypeScript GATE_ACTION / GATE_PERMISSION
        -> Phoenix GateAction
        -> Passport Catalog
  """

  @actions [
${exActions}
  ]

  @threads [
${exThreads}
  ]

  @metadata %{
${exMetadata}
  }

  @doc "Returns every action registered by the cross-runtime Gate contract."
  @spec all() :: [String.t()]
  def all, do: @actions

  @doc "Returns every action registered by the cross-runtime Gate contract."
  @spec actions() :: [String.t()]
  def actions, do: @actions

  @doc "Returns the registered Article threads used by thread-specific requirements."
  @spec threads() :: [String.t()]
  def threads, do: @threads

  @doc "Returns canonical permission metadata for one action, or nil when unknown."
  @spec metadata(String.t()) :: map() | nil
  def metadata(action) when is_binary(action), do: Map.get(@metadata, action)
  def metadata(_action), do: nil

${exFunctions}
end
`

const outputs = [
  [tsTarget, formattedTs],
  [exTarget, ex],
]

if (process.argv.includes('--check')) {
  const mismatches = []
  for (const [target, expected] of outputs) {
    const actual = await readFile(target, 'utf8').catch(() => '')
    if (actual !== expected) mismatches.push(fileURLToPath(target))
  }
  if (mismatches.length) {
    console.error(`Generated Gate contract is stale:\n${mismatches.join('\n')}`)
    process.exitCode = 1
  }
} else {
  await Promise.all(outputs.map(([target, content]) => writeFile(target, content)))
}
