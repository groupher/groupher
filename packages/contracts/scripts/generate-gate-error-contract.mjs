import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const source = JSON.parse(await readFile(new URL('gate-error.contract.json', root), 'utf8'))
const entries = Object.entries(source.errorCodes ?? {})
if (
  entries.length !== 1 ||
  entries[0][0] !== 'COMMUNITY_ADMISSION_CHANGED' ||
  !Number.isSafeInteger(entries[0][1])
) {
  throw new Error('Invalid Gate error contract')
}
const [name, code] = entries[0]
const ts = `// Generated by scripts/generate-gate-error-contract.mjs. Do not edit directly.\nexport const GATE_ERROR_CODE = {\n  ${name}: ${code},\n} as const\n`
const ex = `# Generated by packages/contracts/scripts/generate-gate-error-contract.mjs. Do not edit directly.\ndefmodule GroupherServer.CMS.Gate.ErrorContract do\n  @moduledoc """\n  Registers cross-runtime Gate recovery errors.\n\n      gate-error.contract.json -> ErrorCat and frontend error code\n  """\n  @doc "Registers the binding admission conflict."\n  defmacro define_errors do\n    quote do\n      error(:community_admission_changed, code: ${code}, retryable: true, actions: [:retry], message_key: "cms.gate.community_admission_changed")\n    end\n  end\nend\n`
const outputs = [
  [new URL('src/gate-error.generated.ts', root), ts],
  [new URL('../../backend/api/lib/groupher_server/cms/gate/error_contract.ex', root), ex],
]
if (process.argv.includes('--check')) {
  const stale = []
  for (const [target, expected] of outputs)
    if ((await readFile(target, 'utf8').catch(() => '')) !== expected)
      stale.push(fileURLToPath(target))
  if (stale.length) {
    console.error(`Generated Gate error contract is stale:\n${stale.join('\n')}`)
    process.exitCode = 1
  }
} else await Promise.all(outputs.map(([target, content]) => writeFile(target, content)))
