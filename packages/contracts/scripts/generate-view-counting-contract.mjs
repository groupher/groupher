import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const source = JSON.parse(await readFile(new URL('view-counting.contract.json', root), 'utf8'))
const tsTarget = new URL('src/view-counting.generated.ts', root)

const ts = `// Generated by scripts/generate-view-counting-contract.mjs. Do not edit directly.
export const VIEW_COUNTING_CONTRACT = {
  version: ${source.version},
  humanMinVisibleMs: ${source.humanMinVisibleMs},
} as const
`

const outputs = [[tsTarget, ts]]

if (process.argv.includes('--check')) {
  const mismatches = []
  for (const [target, expected] of outputs) {
    const actual = await readFile(target, 'utf8').catch(() => '')
    if (actual !== expected) mismatches.push(fileURLToPath(target))
  }
  if (mismatches.length) {
    console.error(`Generated view-counting contract is stale:\n${mismatches.join('\n')}`)
    process.exitCode = 1
  }
} else {
  await Promise.all(outputs.map(([target, content]) => writeFile(target, content)))
}
