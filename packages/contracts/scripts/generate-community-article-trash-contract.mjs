import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const contract = JSON.parse(await readFile(new URL('community-article-trash.contract.json', root), 'utf8'))
const threads = contract.threads
const expected = ['post', 'blog', 'changelog', 'doc']
if (Object.keys(contract).join(',') !== 'threads' || !Array.isArray(threads) ||
    JSON.stringify(threads) !== JSON.stringify(expected)) {
  throw new Error('Community Article Trash must declare the fixed supported thread subset')
}

const config = await readFile(new URL('../../backend/api/config/config.exs', root), 'utf8')
const sections = [...config.matchAll(/config\s+:groupher_server,\s*:article,([\s\S]*?)(?=\nconfig\s|\nimport_config\s|$)/g)]
if (sections.length !== 1) throw new Error('Expected exactly one Article config')
const declarations = [...sections[0][1].matchAll(/^\s*threads:\s*\[([^\]]*)\],?\s*$/gm)]
if (declarations.length !== 1) throw new Error('Expected exactly one Article thread declaration')
const tokens = declarations[0][1].split(',').map((token) => token.trim())
if (!tokens.length || tokens.some((token) => !/^:[a-z][a-z0-9_]*$/.test(token))) {
  throw new Error('Invalid Article thread declaration')
}
const known = new Set(tokens.map((token) => token.slice(1)))
if (known.size !== tokens.length || threads.some((thread) => !known.has(thread))) {
  throw new Error('Trash threads must be distinct registered Article threads')
}

const tsTarget = new URL('src/community-article-trash.generated.ts', root)
const exTarget = new URL('../../backend/api/lib/groupher_server/cms/community_article_trash_contract.ex', root)
const ts = `// Generated by scripts/generate-community-article-trash-contract.mjs. Do not edit directly.\nexport const COMMUNITY_ARTICLE_TRASH_THREADS = ${JSON.stringify(threads)} as const\nexport type TCommunityArticleTrashThread = (typeof COMMUNITY_ARTICLE_TRASH_THREADS)[number]\n`
const ex = `# Generated by packages/contracts/scripts/generate-community-article-trash-contract.mjs. Do not edit directly.\ndefmodule GroupherServer.CMS.CommunityArticleTrashContract do\n  @moduledoc \"\"\"\n  Generated Community Article Trash thread values.\n\n      JSON contract -> generated TS / Elixir values -> tests verify GraphQL and query contracts\n  \"\"\"\n\n  @doc \"Returns the supported thread atoms.\"\n  def threads, do: [${threads.map((thread) => `:${thread}`).join(', ')}]\nend\n`
const outputs = [[tsTarget, ts], [exTarget, ex]]
if (process.argv.includes('--check')) {
  const stale = []
  for (const [target, expectedOutput] of outputs) {
    if ((await readFile(target, 'utf8').catch(() => '')) !== expectedOutput) stale.push(fileURLToPath(target))
  }
  if (stale.length) {
    console.error(`Generated Community Article Trash contract is stale:\n${stale.join('\n')}`)
    process.exitCode = 1
  }
} else {
  await Promise.all(outputs.map(([target, output]) => writeFile(target, output)))
}
