import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const repo = path.resolve(root, '../..')
const contract = JSON.parse(readFileSync(path.join(root, 'notice.contract.json'), 'utf8'))
const list = (values) => `[${values.map((value) => `'${value}'`).join(', ')}] as const`
const ts = `// Generated by scripts/generate-notice-contract.mjs. Do not edit directly.
export const NOTICE_CONTRACT_VERSION = ${contract.version} as const
export const NOTICE_ACTIVITY_TYPES = ${list(contract.activityTypes)}
export const NOTICE_REQUEST_TYPES = ${list(contract.requestTypes)}
export const NOTICE_REQUEST_ACTIONS = ${list(contract.requestActions)}
export const NOTICE_REQUEST_EVENTS = ${list(contract.requestEvents)}
export type NoticeActivityType = (typeof NOTICE_ACTIVITY_TYPES)[number]
export type NoticeRequestType = (typeof NOTICE_REQUEST_TYPES)[number]
export type NoticeRequestAction = (typeof NOTICE_REQUEST_ACTIONS)[number]
export type NoticeRequestEvent = (typeof NOTICE_REQUEST_EVENTS)[number]
`
const elixirList = (values) => `[${values.map((value) => `:${value}`).join(', ')}]`
const ex = `# Generated by scripts/generate-notice-contract.mjs. Do not edit directly.
defmodule GroupherServer.Messaging.NoticeContract do
  @moduledoc """
  Generated Notice value sets shared by persistence, validation and migrations.

      packages/contracts/notice.contract.json -> NoticeContract -> Notice schema
  """
  @activity_types ${elixirList(contract.activityTypes)}
  @request_types ${elixirList(contract.requestTypes)}
  @request_actions ${elixirList(contract.requestActions)}
  @request_events ${elixirList(contract.requestEvents)}
  @doc "Returns the supported activity Notice types."
  def activity_types, do: @activity_types
  @doc "Returns the request resource types carried by a Notice."
  def request_types, do: @request_types
  @doc "Returns the request actions carried by a Notice."
  def request_actions, do: @request_actions
  @doc "Returns the request lifecycle event types carried by a Notice."
  def request_events, do: @request_events
end
`
const outputs = [
  [path.join(root, 'src/notice.generated.ts'), ts],
  [path.join(repo, 'backend/api/lib/groupher_server/messaging/notice_contract.generated.ex'), ex],
]

if (process.argv.includes('--check')) {
  const stale = outputs.filter(([file, expected]) => readFileSync(file, 'utf8') !== expected).map(([file]) => file)
  if (stale.length) {
    console.error(`Stale Notice contract outputs:\n${stale.join('\n')}`)
    process.exitCode = 1
  }
} else {
  for (const [file, content] of outputs) writeFileSync(file, content)
}
