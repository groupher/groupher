import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { Country, State } from 'country-state-city'

const REGION_COUNTRIES = ['CN', 'US', 'CA', 'RU', 'AU', 'BR', 'IN', 'ID']
const scriptDir = dirname(fileURLToPath(import.meta.url))
const outputPath = resolve(
  scriptDir,
  '../src/server/visitor-location/visitor-location.generated.ts',
)

const point = ({ latitude, longitude }) => {
  const lat = Number(latitude)
  const lng = Number(longitude)
  return Number.isFinite(lat) && Number.isFinite(lng) ? [lat, lng] : null
}

const countries = Object.fromEntries(
  Country.getAllCountries()
    .map((country) => [country.isoCode, { name: country.name, location: point(country) }])
    .filter(([, value]) => value.location),
)

const regions = Object.fromEntries(
  REGION_COUNTRIES.flatMap((countryCode) =>
    State.getStatesOfCountry(countryCode)
      .map((region) => [
        `${countryCode}-${region.isoCode}`,
        { name: region.name, location: point(region) },
      ])
      .filter(([, value]) => value.location),
  ),
)

const source = `// Generated by scripts/generate-visitor-location-data.mjs. Do not edit manually.
// Source: country-state-city 3.2.1 (MIT). Country and allowlisted region label points only.

export const VISITOR_LOCATION_DATA_VERSION = 'country-state-city@3.2.1'

export const COUNTRY_LOCATION_POINTS = ${JSON.stringify(countries, null, 2)} as const

export const REGION_LOCATION_POINTS = ${JSON.stringify(regions, null, 2)} as const
`

await mkdir(dirname(outputPath), { recursive: true })
await writeFile(outputPath, source)

console.log(
  `Generated ${Object.keys(countries).length} country and ${Object.keys(regions).length} region points.`,
)
